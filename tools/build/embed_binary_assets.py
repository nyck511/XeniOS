#!/usr/bin/env python3
"""Embed a flat asset directory in a deterministic C++ source pair."""

import argparse
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile
from typing import NamedTuple, Optional, Sequence


BYTES_PER_LINE = 16
SYMBOL_INVALID_RE = re.compile(r"[^A-Za-z0-9_]")
NAMESPACE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class AssetGenerationError(RuntimeError):
    """The requested embedded asset source pair could not be generated."""


class Asset(NamedTuple):
    name: str
    symbol: str
    data: bytes


def sanitize_symbol(name: str) -> str:
    symbol = SYMBOL_INVALID_RE.sub("_", name)
    if symbol and symbol[0].isdigit():
        symbol = "_" + symbol
    if not symbol:
        raise AssetGenerationError(
            f"asset filename does not produce a C++ symbol: {name!r}")
    return symbol


def discover_assets(source_dir: Path) -> list[Asset]:
    if not source_dir.is_dir():
        raise AssetGenerationError(
            f"asset source directory is missing: {source_dir}")

    try:
        entries = sorted(source_dir.iterdir(), key=lambda entry: entry.name)
    except OSError as error:
        raise AssetGenerationError(
            f"failed to enumerate asset directory {source_dir}: {error}") from error

    assets = []
    symbols = {}
    for entry in entries:
        try:
            entry_mode = entry.lstat().st_mode
        except OSError as error:
            raise AssetGenerationError(
                f"failed to inspect asset input {entry}: {error}") from error
        if not stat.S_ISREG(entry_mode):
            continue

        symbol = sanitize_symbol(entry.name)
        previous_name = symbols.get(symbol)
        if previous_name is not None:
            raise AssetGenerationError(
                "duplicate sanitized asset symbol "
                f"{symbol!r}: {previous_name!r} and {entry.name!r}")
        symbols[symbol] = entry.name

        try:
            data = entry.read_bytes()
        except OSError as error:
            raise AssetGenerationError(
                f"failed to read asset input {entry}: {error}") from error
        assets.append(Asset(entry.name, symbol, data))

    if not assets:
        raise AssetGenerationError(
            f"asset source directory has no regular files: {source_dir}")
    return assets


def format_byte_array(data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), BYTES_PER_LINE):
        chunk = data[offset:offset + BYTES_PER_LINE]
        rows.append("  " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(rows)


def generate_candidates(
        assets: Sequence[Asset],
        namespace_name: str,
) -> tuple[str, str]:
    full_namespace = f"xe::ui::embedded_{namespace_name}"
    header_lines = [
        "// Auto-generated by tools/build/embed_binary_assets.py.",
        "#pragma once",
        "#include <cstddef>",
        f"namespace {full_namespace} {{",
        "struct Asset {",
        "  const char* name;",
        "  const unsigned char* data;",
        "  size_t size;",
        "};",
    ]
    source_lines = [
        "// Auto-generated by tools/build/embed_binary_assets.py.",
        f'#include "embedded_{namespace_name}.h"',
        f"namespace {full_namespace} {{",
    ]

    for asset in assets:
        header_lines.extend([
            f"extern const unsigned char {asset.symbol}_data[];",
            f"extern const size_t {asset.symbol}_size;",
        ])
        source_lines.extend([
            f"const unsigned char {asset.symbol}_data[] = {{",
            format_byte_array(asset.data),
            "};",
            (
                f"const size_t {asset.symbol}_size = "
                f"sizeof({asset.symbol}_data);"
            ),
        ])

    header_lines.extend([
        "extern const Asset kAll[];",
        "extern const size_t kAllCount;",
        f"}}  // namespace {full_namespace}",
        "",
    ])
    source_lines.append("const Asset kAll[] = {")
    for asset in assets:
        source_lines.append(
            "  {"
            f"{json.dumps(asset.name)}, {asset.symbol}_data, "
            f"sizeof({asset.symbol}_data)"
            "},")
    source_lines.extend([
        "};",
        "const size_t kAllCount = sizeof(kAll) / sizeof(kAll[0]);",
        f"}}  // namespace {full_namespace}",
        "",
    ])
    return "\n".join(header_lines), "\n".join(source_lines)


def validate_candidates(
        header: str,
        source: str,
        assets: Sequence[Asset],
        namespace_name: str,
) -> None:
    full_namespace = f"xe::ui::embedded_{namespace_name}"
    header_requirements = [
        f"namespace {full_namespace} {{",
        "struct Asset {",
        "extern const Asset kAll[];",
        "extern const size_t kAllCount;",
    ]
    source_requirements = [
        f'#include "embedded_{namespace_name}.h"',
        f"namespace {full_namespace} {{",
        "const Asset kAll[] = {",
        "const size_t kAllCount = sizeof(kAll) / sizeof(kAll[0]);",
    ]
    for asset in assets:
        header_requirements.extend([
            f"extern const unsigned char {asset.symbol}_data[];",
            f"extern const size_t {asset.symbol}_size;",
        ])
        source_requirements.extend([
            f"const unsigned char {asset.symbol}_data[] = {{",
            (
                f"const size_t {asset.symbol}_size = "
                f"sizeof({asset.symbol}_data);"
            ),
        ])

    missing_header = [
        requirement for requirement in header_requirements
        if requirement not in header
    ]
    missing_source = [
        requirement for requirement in source_requirements
        if requirement not in source
    ]
    if missing_header or missing_source:
        details = []
        if missing_header:
            details.append(
                "header: " + ", ".join(repr(item) for item in missing_header))
        if missing_source:
            details.append(
                "source: " + ", ".join(repr(item) for item in missing_source))
        raise AssetGenerationError(
            "generated candidate validation failed (" + "; ".join(details) + ")")


def stage_candidate(path: Path, content: str) -> Path:
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
                mode="w",
                encoding="utf-8",
                newline="\n",
                prefix=f".{path.name}.",
                suffix=".tmp",
                dir=path.parent,
                delete=False) as temporary:
            temporary.write(content)
            temporary.flush()
            os.fsync(temporary.fileno())
            temporary_path = Path(temporary.name)
        temporary_path.chmod(0o644)
        if temporary_path.read_text(encoding="utf-8") != content:
            raise AssetGenerationError(
                f"staged candidate validation failed: {temporary_path}")
        return temporary_path
    except OSError as error:
        raise AssetGenerationError(
            f"failed to stage generated output {path}: {error}") from error
    finally:
        if temporary_path is not None and sys.exc_info()[0] is not None:
            try:
                temporary_path.unlink()
            except FileNotFoundError:
                pass


def replace_outputs(
        candidates: Sequence[tuple[Path, str]],
) -> list[tuple[Path, str]]:
    staged = {}
    results = []
    try:
        for path, content in candidates:
            staged[path] = stage_candidate(path, content)

        for path, content in candidates:
            temporary_path = staged[path]
            try:
                unchanged = (
                    path.is_file() and
                    path.read_text(encoding="utf-8") == content
                )
            except OSError as error:
                raise AssetGenerationError(
                    f"failed to compare generated output {path}: {error}") from error
            if unchanged:
                temporary_path.unlink()
                staged.pop(path)
                results.append((path, "unchanged"))
                continue
            try:
                os.replace(temporary_path, path)
            except OSError as error:
                raise AssetGenerationError(
                    f"failed to replace generated output {path}: {error}") from error
            staged.pop(path)
            results.append((path, "generated"))
    finally:
        for temporary_path in staged.values():
            try:
                temporary_path.unlink()
            except OSError:
                pass
    return results


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Embed all immediate regular files in a directory as a "
            "deterministic C++ source pair."
        ))
    parser.add_argument("--source-dir", required=True)
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--namespace", dest="namespace_name", required=True)
    return parser.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    try:
        if not NAMESPACE_RE.fullmatch(args.namespace_name):
            raise AssetGenerationError(
                f"invalid output namespace: {args.namespace_name!r}")

        source_dir = Path(args.source_dir).expanduser().resolve()
        output_dir = Path(args.output_dir).expanduser().resolve()
        assets = discover_assets(source_dir)
        header, source = generate_candidates(assets, args.namespace_name)
        validate_candidates(header, source, assets, args.namespace_name)

        try:
            output_dir.mkdir(parents=True, exist_ok=True)
        except OSError as error:
            raise AssetGenerationError(
                f"failed to create output directory {output_dir}: {error}") from error
        if not output_dir.is_dir():
            raise AssetGenerationError(
                f"asset output path is not a directory: {output_dir}")

        header_path = (
            output_dir / f"embedded_{args.namespace_name}.h").resolve()
        source_path = (
            output_dir / f"embedded_{args.namespace_name}.cc").resolve()
        if header_path.parent != output_dir or source_path.parent != output_dir:
            raise AssetGenerationError(
                "generated output would escape the requested output directory")

        results = replace_outputs([
            (header_path, header),
            (source_path, source),
        ])
        for path, state in results:
            print(f"{state}: {path}")
        print(
            f"Embedded {len(assets)} assets in "
            f"namespace xe::ui::embedded_{args.namespace_name}.")
        return 0
    except AssetGenerationError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
